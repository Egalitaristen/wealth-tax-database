def write_csv(filename, rows, fieldnames):
    p = DATA_DIR / filename
    with open(p, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {filename} ({len(rows)} rows)")

